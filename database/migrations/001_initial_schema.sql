CREATE TABLE IF NOT EXISTS sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    url TEXT NOT NULL UNIQUE,
    publisher TEXT NOT NULL,
    license TEXT NOT NULL,
    accessed_on DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS categories (
    slug TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('derivative', 'integral', 'technique')),
    category_slug TEXT NOT NULL REFERENCES categories (slug),
    expression TEXT NOT NULL,
    result TEXT NOT NULL,
    conditions TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    source_id BIGINT NOT NULL REFERENCES sources (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS entries_kind_category_idx
    ON entries (kind, category_slug);
CREATE INDEX IF NOT EXISTS entries_title_idx
    ON entries (LOWER(title));
