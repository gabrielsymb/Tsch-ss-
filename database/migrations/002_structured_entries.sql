CREATE TABLE IF NOT EXISTS entry_aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES entries (id) ON DELETE CASCADE,
    alias TEXT NOT NULL CHECK (BTRIM(alias) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (entry_id, alias)
);

CREATE UNIQUE INDEX IF NOT EXISTS entry_aliases_normalized_idx
    ON entry_aliases (entry_id, LOWER(alias));

CREATE TABLE IF NOT EXISTS entry_notations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES entries (id) ON DELETE CASCADE,
    label TEXT NOT NULL,
    format TEXT NOT NULL CHECK (format IN ('latex', 'unicode', 'plain_text')),
    notation TEXT NOT NULL CHECK (BTRIM(notation) <> ''),
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (entry_id, format, notation)
);

CREATE UNIQUE INDEX IF NOT EXISTS entry_notations_one_primary_idx
    ON entry_notations (entry_id)
    WHERE is_primary;

CREATE TABLE IF NOT EXISTS entry_examples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES entries (id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    prompt TEXT NOT NULL,
    result TEXT NOT NULL,
    steps TEXT[] NOT NULL DEFAULT '{}',
    sort_order INTEGER NOT NULL DEFAULT 0,
    UNIQUE (entry_id, title)
);

CREATE TABLE IF NOT EXISTS entry_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES entries (id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    field_name TEXT NOT NULL,
    description TEXT NOT NULL,
    example TEXT NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0,
    UNIQUE (entry_id, title)
);

CREATE TABLE IF NOT EXISTS entry_validity_conditions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES entries (id) ON DELETE CASCADE,
    description TEXT NOT NULL CHECK (BTRIM(description) <> ''),
    predicate TEXT NOT NULL DEFAULT '',
    domain TEXT NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0,
    UNIQUE (entry_id, description)
);

CREATE TABLE IF NOT EXISTS entry_sources (
    entry_id BIGINT NOT NULL REFERENCES entries (id) ON DELETE CASCADE,
    source_id BIGINT NOT NULL REFERENCES sources (id) ON DELETE RESTRICT,
    role TEXT NOT NULL CHECK (role IN ('primary', 'supplementary')),
    PRIMARY KEY (entry_id, source_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS entry_sources_one_primary_idx
    ON entry_sources (entry_id)
    WHERE role = 'primary';

CREATE TABLE IF NOT EXISTS entry_relations (
    entry_id BIGINT NOT NULL REFERENCES entries (id) ON DELETE CASCADE,
    related_entry_id BIGINT NOT NULL REFERENCES entries (id) ON DELETE CASCADE,
    relation_type TEXT NOT NULL CHECK (
        relation_type IN ('generalization', 'special_case', 'related', 'prerequisite')
    ),
    PRIMARY KEY (entry_id, related_entry_id, relation_type),
    CHECK (entry_id <> related_entry_id)
);

