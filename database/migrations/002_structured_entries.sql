INSERT INTO entry_validity_conditions (entry_id, description)
SELECT id, conditions
FROM entries
WHERE BTRIM(conditions) <> ''
ON CONFLICT (entry_id, description) DO NOTHING;

INSERT INTO entry_sources (entry_id, source_id, role)
SELECT id, source_id, 'primary'
FROM entries
ON CONFLICT (entry_id, source_id) DO NOTHING;

CREATE INDEX IF NOT EXISTS entry_examples_entry_sort_idx
    ON entry_examples (entry_id, sort_order, id);
CREATE INDEX IF NOT EXISTS entry_applications_entry_sort_idx
    ON entry_applications (entry_id, sort_order, id);
CREATE INDEX IF NOT EXISTS entry_validity_conditions_entry_sort_idx
    ON entry_validity_conditions (entry_id, sort_order, id);
CREATE INDEX IF NOT EXISTS entry_relations_related_idx
    ON entry_relations (related_entry_id);
